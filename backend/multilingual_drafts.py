def num_to_marathi_words(n: int) -> str:
    """Converts numeric amount to formal Marathi legal words."""
    if n <= 0:
        return "शून्य"
    units = {
        1: "एक", 2: "दोन", 3: "तीन", 4: "चार", 5: "पाच", 6: "सहा", 7: "सात", 8: "आठ", 9: "नऊ", 10: "दहा",
        11: "अकरा", 12: "बारा", 13: "तेरा", 14: "चौदा", 15: "पंधरा", 16: "सोळा", 17: "सतरा", 18: "अठरा", 19: "एकोणीस",
        20: "वीस", 25: "पंचवीस", 30: "तीस", 40: "चाळीस", 50: "पन्नास", 60: "साठ", 70: "सत्तर", 80: "ऐंशी", 90: "नव्वद"
    }
    if n in units:
        return units[n]
    if n < 100:
        ten = (n // 10) * 10
        rem = n % 10
        return f"{units.get(ten, str(ten))}शे {units.get(rem, str(rem))}" if ten in units else str(n)
    if n < 1000:
        hundreds = n // 100
        rem = n % 100
        return f"{units.get(hundreds, str(hundreds))} शे " + (num_to_marathi_words(rem) if rem else "")
    if n < 100000:
        thousands = n // 1000
        rem = n % 1000
        return f"{num_to_marathi_words(thousands)} हजार " + (num_to_marathi_words(rem) if rem else "")
    if n < 10000000:
        lakhs = n // 100000
        rem = n % 100000
        return f"{num_to_marathi_words(lakhs)} लाख " + (num_to_marathi_words(rem) if rem else "")
    crores = n // 10000000
    rem = n % 10000000
    return f"{num_to_marathi_words(crores)} कोटी " + (num_to_marathi_words(rem) if rem else "")



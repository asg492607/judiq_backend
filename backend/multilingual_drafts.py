def _extract_case_vars(case_data: Dict[str, Any]):
    """Extract and sanitize case facts with fallback placeholders."""
    today = datetime.now().strftime("%d/%m/%Y")
    complainant = case_data.get("complainant_name") or case_data.get("complainantName") or case_data.get("drawer") or "________ (तक्रारदार / परिवादीचे नाव)"
    complainant_addr = case_data.get("complainant_address") or "________ (तक्रारदार / परिवादीचा पत्ता)"
    accused = case_data.get("accused_name") or case_data.get("accusedName") or case_data.get("payee") or "________ (आरोपी / अभियुक्तचे नाव)"
    accused_addr = case_data.get("accused_address") or "________ (आरोपी / अभियुक्तचा पत्ता)"
    
    # Financial details
    raw_amount = case_data.get("cheque_amount") or case_data.get("amount") or case_data.get("chequeAmount") or 0
    try:
        amount_num = int(float(str(raw_amount).replace(",", "").replace("Rs.", "").strip()))
    except (ValueError, TypeError):
        amount_num = 0
        
    amount_str = f"₹{amount_num:,.0f}/-" if amount_num > 0 else "₹________/-"
    mr_words = f"(अक्षरी रुपये {num_to_marathi_words(amount_num)} फक्त)" if amount_num > 0 else ""
    hi_words = f"(शब्दों में रुपये {num_to_hindi_words(amount_num)} मात्र)" if amount_num > 0 else ""

    # Cheque & Banking details
    cheque_no = case_data.get("cheque_number") or case_data.get("chequeNumber") or "________"
    cheque_date = case_data.get("cheque_date") or case_data.get("chequeDate") or "[धनादेश दिनांक]"
    bank_name = case_data.get("bank_name") or case_data.get("bankName") or "________ बँक"
    branch_name = case_data.get("branch_name") or case_data.get("branch") or "शाखा"
    return_date = case_data.get("dishonour_date") or case_data.get("dishonourDate") or case_data.get("presentation_date") or "[अनादर दिनांक]"
    return_reason = case_data.get("return_reason") or "खात्यात अपुरी रक्कम (Funds Insufficient)"
    notice_date = case_data.get("notice_date") or case_data.get("noticeDate") or "[नोटीस दिनांक]"
    notice_service_date = case_data.get("notice_delivery_date") or case_data.get("noticeReceivedDate") or "[नोटीस बजावणी दिनांक]"
    jurisdiction_court = case_data.get("court_name") or "मा. प्रथम वर्ग न्यायदंडाधिकारी (JMFC) न्यायालय"

    return {
        "today": today,
        "complainant": complainant,
        "complainant_addr": complainant_addr,
        "accused": accused,
        "accused_addr": accused_addr,
        "amount_num": amount_num,
        "amount_str": amount_str,
        "mr_words": mr_words,
        "hi_words": hi_words,
        "cheque_no": cheque_no,
        "cheque_date": cheque_date,
        "bank_name": bank_name,
        "branch_name": branch_name,
        "return_date": return_date,
        "return_reason": return_reason,
        "notice_date": notice_date,
        "notice_service_date": notice_service_date,
        "jurisdiction_court": jurisdiction_court,
    }



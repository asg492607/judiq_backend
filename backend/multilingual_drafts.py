def format_multilingual_draft(draft_type: str, lang: str, case_data: Dict[str, Any], base_text: str = "") -> str:
    """
    Returns a court-ready, lawyer-verified Marathi or Hindi draft based on case facts.
    Guarantees strict statutory formatting and Devanagari numerals/terms.
    """
    v = _extract_case_vars(case_data)
    normalized_lang = str(lang or "en").lower().strip()
    norm_type = str(draft_type or "LEGAL_NOTICE").upper()

    if normalized_lang in ("mr", "marathi"):
        header = "=" * 75 + f"\nमहाराष्ट्र न्यायालयीन विधी मसुदा (मराठी) — {norm_type}\n" + "=" * 75 + "\n\n"
        if norm_type in ("LEGAL_NOTICE", "DEMAND_NOTICE"):
            return header + get_marathi_legal_notice(v)
        elif norm_type in ("COMPLAINT", "CRIMINAL_COMPLAINT"):
            return header + get_marathi_complaint(v)
        elif norm_type in ("APPLICATION_143A", "INTERIM_COMPENSATION"):
            return header + get_marathi_application_143a(v)
        elif norm_type in ("AFFIDAVIT_EXAM_CHIEF", "EVIDENCE_AFFIDAVIT"):
            return header + get_marathi_affidavit_exam_chief(v)
        elif norm_type in ("DELAY_CONDONATION", "CONDONATION_OF_DELAY"):
            return header + get_marathi_delay_condonation(v)
        elif norm_type in ("DEFENCE_REPLY", "NOTICE_REPLY"):
            return header + get_marathi_defence_reply(v)
        elif norm_type in ("REGULAR_BAIL", "ANTICIPATORY_BAIL", "BAIL"):
            return header + get_marathi_bail_application(v)
        elif norm_type in ("SARFAESI_13_2_NOTICE", "SARFAESI_NOTICE"):
            return header + get_marathi_sarfaesi_13_2_notice(v)
        elif norm_type in ("SARFAESI_13_3A_REPLY", "SARFAESI_REPLY"):
            return header + get_marathi_sarfaesi_13_3a_reply(v)
        elif norm_type in ("SARFAESI_SEC_17_SA_PETITION", "SARFAESI_PETITION"):
            return header + get_marathi_sarfaesi_sa_petition(v)
        else:
            return header + get_marathi_legal_notice(v)

    elif normalized_lang in ("hi", "hindi"):
        header = "=" * 75 + f"\nभारतीय न्यायालयीन विधिक प्रारूप (हिंदी) — {norm_type}\n" + "=" * 75 + "\n\n"
        if norm_type in ("LEGAL_NOTICE", "DEMAND_NOTICE"):
            return header + get_hindi_legal_notice(v)
        elif norm_type in ("COMPLAINT", "CRIMINAL_COMPLAINT"):
            return header + get_hindi_complaint(v)
        elif norm_type in ("APPLICATION_143A", "INTERIM_COMPENSATION"):
            return header + get_hindi_application_143a(v)
        elif norm_type in ("AFFIDAVIT_EXAM_CHIEF", "EVIDENCE_AFFIDAVIT"):
            return header + get_hindi_affidavit_exam_chief(v)
        elif norm_type in ("DELAY_CONDONATION", "CONDONATION_OF_DELAY"):
            return header + get_hindi_delay_condonation(v)
        elif norm_type in ("DEFENCE_REPLY", "NOTICE_REPLY"):
            return header + get_hindi_defence_reply(v)
        elif norm_type in ("REGULAR_BAIL", "ANTICIPATORY_BAIL", "BAIL"):
            return header + get_hindi_bail_application(v)
        elif norm_type in ("SARFAESI_13_2_NOTICE", "SARFAESI_NOTICE"):
            return header + get_hindi_sarfaesi_13_2_notice(v)
        elif norm_type in ("SARFAESI_13_3A_REPLY", "SARFAESI_REPLY"):
            return header + get_hindi_sarfaesi_13_3a_reply(v)
        elif norm_type in ("SARFAESI_SEC_17_SA_PETITION", "SARFAESI_PETITION"):
            return header + get_hindi_sarfaesi_sa_petition(v)
        else:
            return header + get_hindi_legal_notice(v)

    return base_text
